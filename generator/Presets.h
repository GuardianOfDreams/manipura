// ---------- STD gaussian computation ----------
// Reference: applyPresetSTD in test_harmonics_v4.html.
// For each harmonic h_i = f0 * (i+1), sum gaussian contributions from all 5
// formants: gauss(dist, width = F * fwidth) × linear_amp_from_dB.
// Clamped to ≤ 1.0; H1 forced to 1.0 (rule H1 — foundation not suppressed).

inline void computeStdGains(const StdFormantSpec& spec,
                            double f0, double fwidth,
                            double* out) {
    for (int i = 0; i < kNumHarmonics; ++i) {
        const double hFreq = f0 * static_cast<double>(i + 1);
        double total = 0.01;
        for (int f = 0; f < 5; ++f) {
            const double dist  = std::abs(hFreq - spec.freqs[f]);
            const double width = spec.freqs[f] * fwidth;
            const double gauss = std::exp(-(dist * dist) / (2.0 * width * width));
            const double linAmp = std::pow(10.0, spec.amps[f] / 20.0);
            total += gauss * linAmp;
        }
        out[i] = std::min(1.0, total);
    }
    out[0] = 1.0;  // rule H1 — baseline always intact
}

